<h3>Fleetsaving</h3>
<p>Fleetsaving means sending your fleet and resources on a mission timed to return when you are online. Choose the mission, speed and destination carefully; different methods have different risks.</p>
<p>One method is a deployment mission that you recall before arrival. Its timing must be planned carefully, especially if a sensor phalanx can observe the destination.</p>
<p>Another method sends recyclers and accompanying ships from a moon to a debris field. Check that the destination is valid and choose a return time that suits your availability.</p>
<p>Moon-to-moon missions are another option because a sensor phalanx cannot scan a moon. No method is a substitute for checking the target, mission and return time.</p>';

